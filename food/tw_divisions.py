def _build_district_aliases() -> dict[str, dict[str, str]]:
    """升格前的舊區名 → 現行區名，逐縣市一張表。

    五個「縣市合併/升格」的直轄市，底下所有「◯◯區」在改制前都是
    ◯◯市 / ◯◯鎮 / ◯◯鄉（例：中壢市→中壢區、板橋市→板橋區）。
    與其手打上百條容易打錯，不如由現行區名機械推導——
    改制的規則就是「換後綴」，這樣涵蓋完整且零打字風險。

    只對這五都做：其他縣市的鄉鎮市從未改過名，多產別名只是噪音。
    """
    merged = ("新北市", "桃園市", "台中市", "台南市", "高雄市")
    out: dict[str, dict[str, str]] = {}
    for city in merged:
        aliases: dict[str, str] = {}
        for district in TW_DISTRICTS[city]:
            stem = district[:-1]          # 去掉「區」
            for suffix in ("市", "鎮", "鄉"):
                aliases[stem + suffix] = district
        out[city] = aliases
    return out


